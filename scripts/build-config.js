/**
 * Build step: config.yaml (single source of truth) ->
 *   - src/config.js      (imported by the Worker)
 *   - public/config.json (fetched by the frontend)
 * Also copies data/locations.json -> public/locations.json.
 *
 * Run: npm run build   (also runs automatically before `npm run dev`/`deploy`)
 */
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import yaml from 'js-yaml'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

function fail(msg) {
  console.error(`build-config: ${msg}`)
  process.exit(1)
}

const raw = readFileSync(join(root, 'config.yaml'), 'utf8')
const config = yaml.load(raw)
if (!config || typeof config !== 'object') fail('config.yaml is empty or invalid')
if (!config.settings?.title) fail('config.settings.title is required')
if (!Array.isArray(config.monitors) || config.monitors.length === 0) {
  fail('config.monitors must be a non-empty list')
}

const seen = new Set()
config.monitors.forEach((m, i) => {
  if (!m.id) fail(`monitors[${i}] is missing "id"`)
  if (seen.has(m.id)) fail(`duplicate monitor id "${m.id}"`)
  seen.add(m.id)
  if (!m.name) fail(`monitor "${m.id}" is missing "name"`)
  if (!m.url) fail(`monitor "${m.id}" is missing "url"`)
  // normalize defaults (same semantics as v1)
  m.method = m.method || 'GET'
  m.expectStatus = m.expectStatus ?? 200
  m.followRedirect = m.followRedirect ?? false
  // linkable defaults to true when unset
  if (m.linkable === undefined) m.linkable = true
  // group is optional; must be a string when present (frontend renders
  // one accordion section per group, in first-appearance order)
  if (m.group !== undefined && typeof m.group !== 'string') {
    fail(`monitor "${m.id}" has a non-string "group"`)
  }
})

if (!Number.isInteger(config.settings.daysInHistogram) || config.settings.daysInHistogram < 1) {
  fail('config.settings.daysInHistogram must be a positive integer')
}

// maintenances: optional list of scheduled maintenance windows, shown on the
// Incidents view (UptimeFlare-style). Display only — the Worker ignores them.
if (config.maintenances !== undefined) {
  if (!Array.isArray(config.maintenances)) fail('config.maintenances must be a list')
  config.maintenances.forEach((mt, i) => {
    if (!mt || typeof mt !== 'object') fail(`maintenances[${i}] must be an object`)
    if (!mt.start || Number.isNaN(Date.parse(mt.start))) {
      fail(`maintenances[${i}] needs a valid "start" (ISO 8601)`)
    }
    if (mt.end !== undefined && Number.isNaN(Date.parse(mt.end))) {
      fail(`maintenances[${i}] has an invalid "end" (ISO 8601)`)
    }
    if (
      mt.monitors !== undefined &&
      (!Array.isArray(mt.monitors) || mt.monitors.some((id) => typeof id !== 'string'))
    ) {
      fail(`maintenances[${i}].monitors must be a list of monitor ids`)
    }
    for (const k of ['title', 'body', 'color']) {
      if (mt[k] !== undefined && typeof mt[k] !== 'string') {
        fail(`maintenances[${i}].${k} must be a string`)
      }
    }
  })
}

mkdirSync(join(root, 'src'), { recursive: true })
mkdirSync(join(root, 'public'), { recursive: true })

writeFileSync(
  join(root, 'src', 'config.js'),
  `// GENERATED by npm run build from config.yaml — do not edit by hand.\nexport default ${JSON.stringify(config, null, 2)}\n`,
)
writeFileSync(
  join(root, 'public', 'config.json'),
  JSON.stringify(config, null, 2) + '\n',
)
copyFileSync(
  join(root, 'data', 'locations.json'),
  join(root, 'public', 'locations.json'),
)

console.log(
  `build-config: wrote src/config.js + public/config.json (${config.monitors.length} monitors)`,
)
