/**
 * cf-workers-status-page v2 — Cloudflare Worker (modules format)
 *
 * - `scheduled` (CRON): checks every monitor, stores results in KV under the
 *   SAME key as v1 (`monitors_data_v1_1`) so existing history is preserved.
 * - `fetch`: serves JSON API; static frontend is served via Workers Static Assets.
 *
 * Notifications: Slack / Telegram / Discord (optional, via Worker secrets).
 */
import config from './config.js' // generated by `npm run build` from config.yaml — do not edit

const KV_KEY = 'monitors_data_v1_1'
const DUMMY_SECRET = 'default-gh-action-secret'

const todayStr = () => new Date().toISOString().split('T')[0]

const secretSet = (env, name) => {
  const v = env[name]
  return typeof v === 'string' && v.length > 0 && v !== DUMMY_SECRET
}

async function getKVMonitors(env) {
  return env.KV_STATUS_PAGE.get(KV_KEY, 'json')
}

async function setKVMonitors(env, data) {
  return env.KV_STATUS_PAGE.put(KV_KEY, JSON.stringify(data))
}

const operationalLabel = (operational) =>
  operational
    ? config.settings.monitorLabelOperational
    : config.settings.monitorLabelNotOperational

// Figure out which Cloudflare PoP runs this check (for "checked from X").
async function getCheckLocation() {
  try {
    const res = await fetch('https://cloudflare-dns.com/dns-query', {
      method: 'OPTIONS',
    })
    const ray = res.headers.get('cf-ray') || ''
    return ray.split('-')[1] || 'UNKNOWN'
  } catch {
    return 'UNKNOWN'
  }
}

async function notifySlack(env, monitor, operational) {
  const payload = {
    attachments: [
      {
        fallback: `Monitor ${monitor.name} changed status to ${operationalLabel(operational)}`,
        color: operational ? '#36a64f' : '#f2c744',
        blocks: [
          {
            type: 'section',
            text: {
              type: 'mrkdwn',
              text: `Monitor *${monitor.name}* changed status to *${operationalLabel(operational)}*`,
            },
          },
          {
            type: 'context',
            elements: [
              {
                type: 'mrkdwn',
                text: `${operational ? ':white_check_mark:' : ':x:'} \`${
                  monitor.method || 'GET'
                } ${monitor.url}\` - :eyes: <${config.settings.url}|Status Page>`,
              },
            ],
          },
        ],
      },
    ],
  }
  return fetch(env.SECRET_SLACK_WEBHOOK_URL, {
    body: JSON.stringify(payload),
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
  })
}

async function notifyTelegram(env, monitor, operational) {
  const text =
    `Monitor *${monitor.name.replaceAll('-', '\\-')}* changed status to *${operationalLabel(operational)}*\n` +
    `${operational ? '✅' : '❌'} \`${monitor.method || 'GET'} ${monitor.url}\` \\- 👀 [Status Page](${config.settings.url})`

  const payload = new FormData()
  payload.append('chat_id', env.SECRET_TELEGRAM_CHAT_ID)
  payload.append('parse_mode', 'MarkdownV2')
  payload.append('text', text)

  return fetch(
    `https://api.telegram.org/bot${env.SECRET_TELEGRAM_API_TOKEN}/sendMessage`,
    { body: payload, method: 'POST' },
  )
}

async function notifyDiscord(env, monitor, operational) {
  const payload = {
    username: `${config.settings.title}`,
    avatar_url: `${config.settings.url}/${config.settings.logo}`,
    embeds: [
      {
        title: `${monitor.name} is ${operationalLabel(operational)} ${
          operational ? ':white_check_mark:' : ':x:'
        }`,
        description: `\`${monitor.method || 'GET'} ${monitor.url}\` - :eyes: [Status Page](${
          config.settings.url
        })`,
        color: operational ? 3581519 : 13632027,
      },
    ],
  }
  return fetch(env.SECRET_DISCORD_WEBHOOK_URL, {
    body: JSON.stringify(payload),
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
  })
}

/**
 * Run one full check cycle. Same KV data shape as v1 so old history keeps rendering.
 */
export async function processChecks(env, ctx) {
  const checkLocation = await getCheckLocation()
  const checkDay = todayStr()

  let monitorsState = await getKVMonitors(env)
  if (!monitorsState) {
    monitorsState = { lastUpdate: {}, monitors: {} }
  }
  monitorsState.lastUpdate.allOperational = true

  const configIds = new Set(config.monitors.map((m) => m.id))

  for (const monitor of config.monitors) {
    if (typeof monitorsState.monitors[monitor.id] === 'undefined') {
      monitorsState.monitors[monitor.id] = {
        firstCheck: checkDay,
        lastCheck: {},
        checks: {},
        latency: [],
      }
    }

    console.log(`Checking ${monitor.name} ...`)

    const init = {
      method: monitor.method || 'GET',
      redirect: monitor.followRedirect ? 'follow' : 'manual',
      headers: {
        'User-Agent': config.settings.user_agent || 'cf-worker-status-page',
      },
    }

    let checkResponse
    let requestTime = 0
    try {
      const t0 = Date.now()
      checkResponse = await fetch(monitor.url, init)
      requestTime = Math.round(Date.now() - t0)
    } catch (e) {
      // treat network/DNS failure as a failed check
      checkResponse = { status: 0, statusText: String((e && e.message) || e) }
    }

    const monitorOperational =
      checkResponse.status === (monitor.expectStatus || 200)
    const monitorStatusChanged =
      monitorsState.monitors[monitor.id].lastCheck.operational !==
      monitorOperational

    monitorsState.monitors[monitor.id].lastCheck = {
      status: checkResponse.status,
      statusText: checkResponse.statusText,
      operational: monitorOperational,
    }

    if (monitorStatusChanged && secretSet(env, 'SECRET_SLACK_WEBHOOK_URL')) {
      ctx.waitUntil(notifySlack(env, monitor, monitorOperational))
    }
    if (
      monitorStatusChanged &&
      secretSet(env, 'SECRET_TELEGRAM_API_TOKEN') &&
      secretSet(env, 'SECRET_TELEGRAM_CHAT_ID')
    ) {
      ctx.waitUntil(notifyTelegram(env, monitor, monitorOperational))
    }
    if (monitorStatusChanged && secretSet(env, 'SECRET_DISCORD_WEBHOOK_URL')) {
      ctx.waitUntil(notifyDiscord(env, monitor, monitorOperational))
    }

    if (
      (config.settings.collectResponseTimes || !monitorOperational) &&
      !Object.prototype.hasOwnProperty.call(
        monitorsState.monitors[monitor.id].checks,
        checkDay,
      )
    ) {
      monitorsState.monitors[monitor.id].checks[checkDay] = {
        fails: 0,
        res: {},
      }
    }

    if (config.settings.collectResponseTimes && monitorOperational) {
      const dayRes = monitorsState.monitors[monitor.id].checks[checkDay].res
      if (!Object.prototype.hasOwnProperty.call(dayRes, checkLocation)) {
        dayRes[checkLocation] = { n: 0, ms: 0, a: 0 }
      }
      const loc = dayRes[checkLocation]
      loc.n += 1
      loc.ms += requestTime
      loc.a = Math.round(loc.ms / loc.n)
    } else if (!monitorOperational) {
      monitorsState.lastUpdate.allOperational = false
      const dayChecks = monitorsState.monitors[monitor.id].checks[checkDay]
      if (monitorStatusChanged || dayChecks.fails === 0) {
        dayChecks.fails++
      }
    }

    // GĐ4: 12h intraday latency ring buffer (UptimeFlare-style). Appended on
    // successful checks only — failed checks leave a gap in the chart.
    // Trimmed to the last 12h. Rides the existing single KV write per cycle.
    if (monitorOperational) {
      const mst = monitorsState.monitors[monitor.id]
      if (!Array.isArray(mst.latency)) mst.latency = []
      const nowSec = Math.floor(Date.now() / 1000)
      mst.latency.push({ t: nowSec, ms: requestTime, loc: checkLocation })
      const keepFrom = nowSec - 12 * 3600
      while (mst.latency.length > 0 && mst.latency[0].t < keepFrom) {
        mst.latency.shift()
      }
    }
  }

  // GC (replaces the old post-deploy kv-gc script): drop monitors removed from
  // config and trim days older than daysInHistogram.
  const cutoff = new Date()
  cutoff.setDate(cutoff.getDate() - config.settings.daysInHistogram)
  const cutoffStr = cutoff.toISOString().split('T')[0]
  for (const id of Object.keys(monitorsState.monitors)) {
    if (!configIds.has(id)) {
      delete monitorsState.monitors[id]
      continue
    }
    const checks = monitorsState.monitors[id].checks || {}
    for (const day of Object.keys(checks)) {
      if (day < cutoffStr) delete checks[day]
    }
  }

  monitorsState.lastUpdate.time = Date.now()
  monitorsState.lastUpdate.loc = checkLocation

  await setKVMonitors(env, monitorsState)
  return new Response('OK')
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url)

    if (url.pathname === '/api/state') {
      const state = (await getKVMonitors(env)) || {
        lastUpdate: {},
        monitors: {},
      }
      return Response.json({
        monitors: state.monitors || {},
        lastUpdate: state.lastUpdate || {},
      })
    }

    if (url.pathname === '/api/conn') {
      // Connection diagnostics for the QUIC/TLS tools: what the edge saw.
      // No KV, no secrets. httpProtocol is "h3"/"HTTP/3" when the client
      // arrived over QUIC — the basis of the QUIC support test.
      const cf = request.cf || {}
      return Response.json({
        httpProtocol: cf.httpProtocol || null,
        tlsVersion: cf.tlsVersion || null,
        tlsCipher: cf.tlsCipher || null,
        colo: cf.colo || null,
        country: cf.country || null,
        city: cf.city || null,
        asOrganization: cf.asOrganization || null,
        asn: cf.asn || null,
        latitude: cf.latitude || null,
        longitude: cf.longitude || null,
        ip:
          request.headers.get('cf-connecting-ip') ||
          request.headers.get('x-forwarded-for') ||
          null,
      })
    }

    if (url.pathname === '/api/check' && request.method === 'POST') {
      // External trigger (GitHub Actions) so checks run from the placed
      // colo (Singapore) instead of a random global colo.
      const secret = env.CHECK_SECRET || ''
      const auth = request.headers.get('authorization') || ''
      if (!secret || secret === 'default-gh-action-secret' || auth !== `Bearer ${secret}`) {
        return new Response(secret ? 'Unauthorized' : 'Check endpoint not configured', { status: secret ? 401 : 503 })
      }
      ctx.waitUntil(processChecks(env, ctx))
      return new Response('Accepted', { status: 202 })
    }

    if (url.pathname === '/speedtest/upload' && request.method === 'POST') {
      // Speedtest upload probe: read and discard the body, report bytes.
      // No KV writes; used by the Speedtest tab's upload measurement.
      // Capped: a malicious huge body would burn Worker CPU/memory.
      const MAX_UPLOAD_BYTES = 64 * 1024 * 1024
      let received = 0
      try {
        for await (const chunk of request.body) {
          received += chunk.byteLength
          if (received > MAX_UPLOAD_BYTES) {
            return Response.json({ error: 'body too large' }, { status: 413 })
          }
        }
      } catch (e) {
        return Response.json({ error: 'failed to read body' }, { status: 400 })
      }
      return Response.json({ received })
    }

    return new Response('Not found', { status: 404 })
  },

  async scheduled(event, env, ctx) {
    ctx.waitUntil(processChecks(env, ctx))
  },
}
